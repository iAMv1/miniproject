"""MindPulse — Dataset Repair Script.

Rebuilds real_dataset_balanced.csv with:
  - valid ISO timestamps (the legacy file contains 2024-01-33 style dates)
  - no negative values for non-negative features
  - explicit provenance columns (source_type, source_subject, label_origin)
  - synthetic rows regenerated by the CURRENT generator (reproducible, seeded)

Legacy files are preserved as *_legacy.csv, never silently overwritten.

Usage:
    python scripts/repair_datasets.py
"""

from __future__ import annotations

import os
import shutil
from datetime import datetime, timedelta, timezone

import numpy as np
import pandas as pd

ARTIFACTS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "ml", "artifacts")
REAL_CSV = os.path.join(ARTIFACTS_DIR, "real_dataset.csv")
BALANCED_CSV = os.path.join(ARTIFACTS_DIR, "real_dataset_balanced.csv")

SYNTHETIC_GENERATOR_VERSION = "current (synthetic_data.py, seed=42)"


def load_real() -> pd.DataFrame:
    df = pd.read_csv(REAL_CSV)
    assert len(df) == 70, f"expected 70 real rows, got {len(df)}"
    assert set(df["label"].unique()) == {1}, (
        "real dataset must be label=1 only; refusing to guess labels"
    )
    return df


def generate_synthetic_rows(n_neutral: int = 35, n_stressed: int = 35) -> pd.DataFrame:
    import importlib.util
    import sys
    import types

    try:
        import psutil  # noqa: F401
    except ImportError:
        psutil_stub = types.ModuleType("psutil")
        psutil_stub.cpu_percent = lambda *a, **k: 5.0
        psutil_stub.virtual_memory = lambda *a, **k: types.SimpleNamespace(percent=50.0)
        psutil_stub.cpu_count = lambda *a, **k: 8
        sys.modules["psutil"] = psutil_stub

    # Load app.ml modules by path so xgboost (uninstalled here) is never imported.
    app_pkg = types.ModuleType("app")
    app_pkg.__path__ = []
    ml_pkg = types.ModuleType("app.ml")
    ml_pkg.__path__ = []
    sys.modules["app"] = app_pkg
    sys.modules["app.ml"] = ml_pkg

    ml_dir = os.path.normpath(
        os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "ml")
    )

    def load(name: str, filename: str):
        spec = importlib.util.spec_from_file_location(
            f"app.ml.{name}", os.path.join(ml_dir, filename)
        )
        module = importlib.util.module_from_spec(spec)
        sys.modules[f"app.ml.{name}"] = module
        spec.loader.exec_module(module)
        return module

    data_collector = load("data_collector", "data_collector.py")
    feature_extractor = load("feature_extractor", "feature_extractor.py")
    synthetic_data = load("synthetic_data", "synthetic_data.py")

    FEATURE_NAMES = feature_extractor.FEATURE_NAMES
    X, y, _ = synthetic_data.generate_synthetic_dataset(n_samples=4000, random_seed=42)
    df = pd.DataFrame(X, columns=FEATURE_NAMES)
    df["label"] = y

    neutral = df[df["label"] == 0].head(n_neutral).copy()
    stressed = df[df["label"] == 2].head(n_stressed).copy()
    synth = pd.concat([neutral, stressed], ignore_index=True)

    synth["user_id"] = np.where(
        synth["label"] == 0, "synthetic_neutral", "synthetic_stressed"
    )
    return synth


def clamp_non_negative(df: pd.DataFrame) -> pd.DataFrame:
    non_negative = [
        "hold_time_mean", "hold_time_std", "hold_time_median",
        "flight_time_mean", "flight_time_std", "typing_speed_wpm",
        "error_rate", "pause_frequency", "pause_duration_mean",
        "burst_length_mean", "mouse_speed_mean", "mouse_speed_std",
        "direction_change_rate", "click_count", "rage_click_count",
        "scroll_velocity_std", "tab_switch_freq", "session_fragmentation",
        "session_duration_min",
    ]
    for col in non_negative:
        df[col] = df[col].clip(lower=0.0)
    return df


def assign_valid_timestamps(df: pd.DataFrame, start: datetime, step_min: int) -> pd.DataFrame:
    timestamps = [start + timedelta(minutes=i * step_min) for i in range(len(df))]
    df["timestamp"] = [t.isoformat() for t in timestamps]
    return df


def add_provenance(df: pd.DataFrame) -> pd.DataFrame:
    df["source_type"] = np.where(
        df["user_id"].str.startswith("synthetic"), "synthetic", "real"
    )
    df["source_subject"] = df["user_id"]
    df["label_origin"] = np.where(
        df["source_type"] == "synthetic", "generator_label", "original_label"
    )
    df["synthetic_generator_version"] = np.where(
        df["source_type"] == "synthetic", SYNTHETIC_GENERATOR_VERSION, "n/a"
    )
    return df


def main() -> None:
    real = load_real()
    synth = generate_synthetic_rows()
    balanced = pd.concat([real, synth], ignore_index=True)

    balanced = clamp_non_negative(balanced)
    balanced = assign_valid_timestamps(
        balanced, datetime(2026, 1, 1, tzinfo=timezone.utc), step_min=10
    )
    balanced = add_provenance(balanced)

    for legacy in (BALANCED_CSV,):
        if os.path.exists(legacy):
            shutil.copy2(legacy, legacy.replace(".csv", "_legacy.csv"))

    balanced.to_csv(BALANCED_CSV, index=False)

    dist = balanced.groupby(["source_type", "label"]).size()
    print("Written:", BALANCED_CSV)
    print(balanced[["label", "user_id", "timestamp"]].head(3).to_string())
    print("Class/source distribution:")
    print(dist.to_string())
    print("Negative values remaining:",
          int((balanced[balanced["source_type"] == "synthetic"]
               [["click_count", "tab_switch_freq"]].to_numpy() < 0).sum()))


if __name__ == "__main__":
    main()
